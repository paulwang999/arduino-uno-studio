import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const officialRoot = process.argv[2] ? path.resolve(process.argv[2]) : null
const officialCommit = process.argv[3] || 'unknown'

if (!officialRoot) {
  throw new Error('Usage: node scripts/generate-examples.mjs <arduino-examples/examples> <commit>')
}

const boardSpecificBuiltIns = new Set([
  '03.Analog/AnalogWriteMega/AnalogWriteMega.ino',
  '04.Communication/MultiSerial/MultiSerial.ino',
  '04.Communication/SerialPassthrough/SerialPassthrough.ino',
])

const categoryLabels = {
  '01.Basics': '01. Basics',
  '02.Digital': '02. Digital',
  '03.Analog': '03. Analog',
  '04.Communication': '04. Communication',
  '05.Control': '05. Control Structures',
  '06.Sensors': '06. Sensors',
  '07.Display': '07. Display',
  '08.Strings': '08. Strings',
  '09.USB': '09. USB',
  '10.StarterKit_BasicKit': '10. Starter Kit',
  '11.ArduinoISP': '11. Arduino ISP',
}

function displayName(fileName) {
  const projectMatch = fileName.match(/^p(\d+)_(.*)$/i)
  const baseName = projectMatch ? projectMatch[2] : fileName
  const words = baseName
    .replace(/_/g, ' ')
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1 $2')
    .replace(/^tone\b/i, 'Tone')
    .replace(/\bAscii\b/gi, 'ASCII')
    .replace(/\bIsp\b/gi, 'ISP')
    .replace(/\bI2c\b/gi, 'I2C')
    .replace(/\bEeprom\b/gi, 'EEPROM')
    .replace(/\bSpi\b/gi, 'SPI')
    .trim()
  return projectMatch ? `Project ${projectMatch[1]}: ${words}` : words
}

async function findInoFiles(root) {
  const files = []
  async function visit(directory) {
    const entries = await readdir(directory, { withFileTypes: true })
    for (const entry of entries) {
      const fullPath = path.join(directory, entry.name)
      if (entry.isDirectory()) await visit(fullPath)
      else if (entry.isFile() && entry.name.endsWith('.ino')) files.push(fullPath)
    }
  }
  await visit(root)
  return files.sort((a, b) => a.localeCompare(b, 'en'))
}

function normalizePath(value) {
  return value.split(path.sep).join('/')
}

async function readSketchCode(filePath) {
  let code = await readFile(filePath, 'utf8')
  const sketchDirectory = path.dirname(filePath)
  const localIncludes = [...code.matchAll(/^[ \t]*#include[ \t]+"([^"]+)"[ \t]*$/gm)]
  for (const include of localIncludes) {
    const headerPath = path.resolve(sketchDirectory, include[1])
    if (path.dirname(headerPath) !== sketchDirectory) continue
    try {
      const header = await readFile(headerPath, 'utf8')
      code = code.replace(include[0], `// Included from ${include[1]} for the single-file editor.\n${header}`)
    } catch {
      // The Arduino compiler will report a missing local file during the example test.
    }
  }
  return code
}

const examples = []
for (const filePath of await findInoFiles(officialRoot)) {
  const relativePath = normalizePath(path.relative(officialRoot, filePath))
  const [category] = relativePath.split('/')
  const fileName = path.basename(filePath)
  const baseName = path.basename(filePath, '.ino')
  examples.push({
    id: `builtin:${relativePath.replace(/\.ino$/, '')}`,
    name: displayName(baseName),
    fileName,
    category: categoryLabels[category] || category.replace(/^(\d+)\./, '$1. '),
    collection: 'Arduino Built-in',
    compatibility: category === '09.USB' || boardSpecificBuiltIns.has(relativePath) ? 'board-specific' : 'uno',
    code: await readSketchCode(filePath),
    sourceUrl: `https://github.com/arduino/arduino-examples/blob/${officialCommit}/examples/${relativePath}`,
  })
}

const libraryRoots = [
  path.join(projectRoot, '.runtime', 'data', 'packages', 'arduino', 'hardware', 'avr', '1.8.8', 'libraries'),
  path.join(projectRoot, '.runtime', 'user', 'libraries'),
]

for (const libraryRoot of libraryRoots) {
  for (const filePath of await findInoFiles(libraryRoot)) {
    const relativePath = normalizePath(path.relative(libraryRoot, filePath))
    const [libraryName] = relativePath.split('/')
    const fileName = path.basename(filePath)
    const baseName = path.basename(filePath, '.ino')
    examples.push({
      id: `library:${relativePath.replace(/\.ino$/, '')}`,
      name: displayName(baseName),
      fileName,
      category: `Library: ${libraryName}`,
      collection: 'Bundled Library',
      compatibility: 'uno',
      code: await readSketchCode(filePath),
    })
  }
}

const output = `// Generated by scripts/generate-examples.mjs. Do not edit by hand.\n` +
  `import type { ArduinoExample } from './exampleTypes'\n\n` +
  `export const officialExamplesCommit = ${JSON.stringify(officialCommit)}\n\n` +
  `export const generatedExamples: ArduinoExample[] = ${JSON.stringify(examples, null, 2)}\n`

await writeFile(path.join(projectRoot, 'src', 'generatedExamples.ts'), output)
console.log(`Generated ${examples.length} examples (${officialExamplesCommitLabel()}).`)

function officialExamplesCommitLabel() {
  return `${examples.filter((example) => example.collection === 'Arduino Built-in').length} official, ` +
    `${examples.filter((example) => example.collection === 'Bundled Library').length} library`
}
