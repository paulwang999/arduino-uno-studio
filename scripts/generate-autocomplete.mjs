import { access, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const runtime = path.join(root, '.runtime')
const output = path.join(root, 'src', 'generatedArduinoKeywords.ts')
const libraryRoots = [
  path.join(runtime, 'data', 'packages', 'arduino', 'hardware', 'avr', '1.8.8', 'libraries'),
  path.join(runtime, 'user', 'libraries'),
]

async function exists(target) {
  try {
    await access(target)
    return true
  } catch {
    return false
  }
}

async function libraryDirectories() {
  const directories = []
  for (const libraryRoot of libraryRoots) {
    if (!await exists(libraryRoot)) continue
    for (const entry of await readdir(libraryRoot, { withFileTypes: true })) {
      if (entry.isDirectory()) directories.push(path.join(libraryRoot, entry.name))
    }
  }
  return directories
}

async function libraryName(directory) {
  const propertiesPath = path.join(directory, 'library.properties')
  if (!await exists(propertiesPath)) return path.basename(directory)
  const properties = await readFile(propertiesPath, 'utf8')
  return /^name=(.+)$/m.exec(properties)?.[1].trim() || path.basename(directory)
}

async function readKeywords(directory, name) {
  const keywordsPath = path.join(directory, 'keywords.txt')
  if (!await exists(keywordsPath)) return []
  const source = await readFile(keywordsPath, 'utf8')
  return source.split(/\r?\n/).flatMap((line) => {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) return []
    const [keyword, tokenType = 'KEYWORD2'] = trimmed.split(/\s+/)
    if (!/^[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*$/.test(keyword)) return []
    return [{ name: keyword, library: name, tokenType }]
  })
}

async function readHeaders(directory) {
  const propertiesPath = path.join(directory, 'library.properties')
  if (await exists(propertiesPath)) {
    const properties = await readFile(propertiesPath, 'utf8')
    const includes = /^includes=(.+)$/m.exec(properties)?.[1]
    if (includes) return includes.split(',').map((header) => header.trim()).filter(Boolean)
  }
  const sourceDirectory = await exists(path.join(directory, 'src')) ? path.join(directory, 'src') : directory
  return (await readdir(sourceDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith('.h'))
    .map((entry) => entry.name)
}

const keywords = []
const headers = new Set(['Arduino.h'])
for (const directory of await libraryDirectories()) {
  const name = await libraryName(directory)
  keywords.push(...await readKeywords(directory, name))
  for (const header of await readHeaders(directory)) headers.add(header)
}

const uniqueKeywords = [...new Map(keywords.map((keyword) => [`${keyword.library}:${keyword.name}`, keyword])).values()]
  .sort((left, right) => left.name.localeCompare(right.name) || left.library.localeCompare(right.library))
const generated = `// Generated by scripts/generate-autocomplete.mjs. Do not edit by hand.\n\nexport type GeneratedArduinoKeyword = {\n  name: string\n  library: string\n  tokenType: string\n}\n\nexport const generatedArduinoKeywords: GeneratedArduinoKeyword[] = ${JSON.stringify(uniqueKeywords, null, 2)}\n\nexport const generatedArduinoHeaders = ${JSON.stringify([...headers].sort(), null, 2)} as const\n`
const previous = await exists(output) ? await readFile(output, 'utf8') : ''
if (generated !== previous) await writeFile(output, generated, 'utf8')
console.log(`Generated ${uniqueKeywords.length} Arduino library keywords and ${headers.size} headers.`)
