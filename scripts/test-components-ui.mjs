import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdtemp, mkdir, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const { _electron } = require(process.env.STUDIO_PLAYWRIGHT || 'playwright')
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const profile = await mkdtemp(path.join(os.tmpdir(), 'studio-components-ui-'))
const env = { ...process.env }
delete env.ELECTRON_RUN_AS_NODE
delete env.VITE_DEV_SERVER_URL
delete env.ARDUINO_STUDIO_SMOKE_TEST
const executablePath = process.env.STUDIO_EXE || require('electron')
const args = process.env.STUDIO_EXE ? [`--user-data-dir=${profile}`] : [root, `--user-data-dir=${profile}`]
const app = await _electron.launch({ executablePath, args, env })
try {
  const page = await app.firstWindow()
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 960))
  await page.locator('.monaco-editor').waitFor()
  for (const type of ['pir', 'ntc', 'slide-switch', 'joystick', 'rgb-led']) {
    await page.getByTitle('Add component', { exact: true }).click()
    await page.locator(`[data-catalog-id="${type}"]`).click()
    assert.equal(await page.locator(`[data-component="${type}"]`).count(), 1)
  }
  await page.getByTitle('Maximize circuit', { exact: true }).click()
  const stage = await page.locator('.circuit-stage').boundingBox()
  await page.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2)
  await page.mouse.wheel(300, 300)
  await page.waitForTimeout(300)
  const pir = page.locator('[data-component="pir"]')
  await pir.getByRole('checkbox').check()
  assert.equal(await pir.getByRole('checkbox').isChecked(), true)
  const ntc = page.locator('[data-component="ntc"]')
  await ntc.locator('input[type="range"]').evaluate((input) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, '60')
    input.dispatchEvent(new Event('input', { bubbles: true }))
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  assert.match(await ntc.innerText(), /60/)
  const slide = page.locator('[data-component="slide-switch"]')
  await slide.locator('.sensor-toggle input').check()
  assert.match(await slide.innerText(), /2 - 3/)
  const joystick = page.locator('[data-component="joystick"]')
  await joystick.getByRole('checkbox').check()
  await joystick.getByTitle('Center joystick').click()
  assert.equal(await joystick.getByRole('checkbox').isChecked(), false)
  const heading = pir.locator('.circuit-node-heading')
  const from = await heading.boundingBox()
  await page.mouse.move(from.x + 15, from.y + 8)
  await page.mouse.down()
  await page.mouse.move(from.x + 50, from.y + 25, { steps: 5 })
  await page.mouse.up()
  assert.notEqual((await heading.boundingBox()).x, from.x)
  await page.locator('[data-terminal-id="rgb-led-1:R"]').click()
  await page.locator('[data-terminal-id="uno:D9"]').click()
  assert.equal(await page.locator('.wire-hit[data-wire-from="rgb-led-1:R"][data-wire-to="uno:D9"]').count(), 1)
  await page.locator('input[type="color"]').focus()
  await page.keyboard.press('Delete')
  assert.equal(await page.locator('.wire-hit[data-wire-from="rgb-led-1:R"][data-wire-to="uno:D9"]').count(), 1, 'Delete must be ignored in an input')
  await page.locator('.wire-hit[data-wire-from="rgb-led-1:R"][data-wire-to="uno:D9"]').dispatchEvent('click')
  await page.locator('.wire-hit[data-wire-from="rgb-led-1:R"][data-wire-to="uno:D9"]').focus()
  await page.getByLabel('Wire properties').waitFor()
  await page.keyboard.press('Delete')
  assert.equal(await page.locator('.wire-hit[data-wire-from="rgb-led-1:R"][data-wire-to="uno:D9"]').count(), 0, 'Delete must remove the selected wire')
  await page.locator('[data-terminal-id="rgb-led-1:R"]').click()
  await page.locator('[data-terminal-id="uno:D9"]').click()
  await page.getByTitle('Close wire editor').click()
  const renderedAssets = await page.locator('.new-part-visual').evaluateAll((items) => items.every((item) => item.firstElementChild.shadowRoot?.querySelector('svg')))
  assert.equal(renderedAssets, true, 'A new component visual is blank')
  await mkdir(path.join(root, 'outputs'), { recursive: true })
  await page.screenshot({ path: path.join(root, 'outputs', 'components-1.4.0-circuit.png') })
  await page.getByTitle('Restore workspace', { exact: true }).click()
  await page.locator('[data-toolbox-category="input"]').click()
  for (const id of ['pir-motion', 'ntc-temperature', 'slide-switch-read', 'joystick-read']) assert.equal(await page.locator(`[data-snippet-id="${id}"]`).count(), 1)
  const before = await page.locator('.view-lines').innerText()
  await page.locator('[data-snippet-id="pir-motion"]').click()
  assert.equal(await page.locator('.view-lines').innerText(), before, 'Click must not insert a snippet')
  const data = await page.evaluateHandle(() => { const transfer = new DataTransfer(); transfer.setData('application/x-arduino-snippet', 'pir-motion'); return transfer })
  await page.locator('.monaco-editor').dispatchEvent('drop', { dataTransfer: data })
  await page.waitForFunction(() => document.querySelector('.view-lines').textContent.includes('motionDetected'))
  await page.getByRole('button', { name: 'Examples', exact: true }).click()
  for (const id of ['pir-motion', 'ntc-temperature', 'slide-switch-read', 'joystick-read', 'rgb-color']) assert.equal(await page.locator(`[data-example-id="studio:${id}"]`).count(), 1)
  await page.locator('[data-example-id="studio:pir-motion"]').click()
  await page.getByRole('button', { name: 'Run', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.circuit-toolbar strong')?.textContent.includes('RUNNING'), { timeout: 60000 })
  await page.getByRole('button', { name: 'Serial', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.serial-content pre')?.textContent.includes('1'), { timeout: 20000 })
  await page.getByRole('button', { name: 'Uno Lab', exact: true }).click()
  assert.equal(await page.locator('.lab-sensor').count(), 5)
  await page.getByRole('button', { name: 'Circuit', exact: true }).click()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1100, 780))
  await page.waitForTimeout(500)
  await page.screenshot({ path: path.join(root, 'outputs', 'components-1.4.0-compact.png') })
  assert.deepEqual(errors, [])
  console.log('UI tests passed: five rendered parts, controls, drag, wire, drag-only snippets, examples, real Run/Serial, Uno Lab, two window sizes.')
} finally {
  await app.close()
  await rm(profile, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 })
}
